"""Generate wiki/index.md from page frontmatter. Never edit index.md by hand.

Layout: a short map of topics, grouped by domain when meta/vault.json declares domains (in its order;
sub-topics under their parent). Then one section per domain, holding one collapsed Obsidian callout per
topic: the hub first, then pages by type (in vault.json order; sources split primary/secondary),
alphabetical within each group, each line `- [[Page]]: summary`. A page in several topics is listed under
each. Then vault-wide sections for raw files not yet ingested and for assets.

The output is deterministic: running it twice gives the same file, and its updated: date is the
newest updated: among the pages, so regenerating without page changes produces no diff.

Usage:
  python tools/build_index.py           # report whether index.md is up to date
  python tools/build_index.py --write   # regenerate it
"""
import argparse

from vaultlib import (CONFIG, DOMAINS, RAW, ROOT, TYPES, WIKI, raw_provenance, split_frontmatter, topic_registry,
                      topic_domains, utf8_stdout, wiki_pages)


def line(p):
    return f"- [[{p.name}]]: {p.summary or '(no summary)'}"


def topic_order(registry):
    """Top-level topics alphabetically by hub name, each followed by its children."""
    hub_of = {slug: hubs[0] for slug, hubs in registry.items()}
    children = {}
    for slug, hub in hub_of.items():
        children.setdefault(str(hub.meta.get("parent", "")).strip(), []).append(slug)
    ordered = []

    def visit(parent, depth):
        for slug in sorted(children.get(parent, []), key=lambda s: hub_of[s].name.lower()):
            ordered.append((slug, depth))
            visit(slug, depth + 1)
    visit("", 0)
    seen = {s for s, _ in ordered}
    ordered += [(s, 0) for s in sorted(hub_of) if s not in seen]  # parent cycles or unknown parents
    return ordered, hub_of


def raw_sections(pages):
    referenced, superseded = raw_provenance(pages)
    pending, assets = [], []
    for f in sorted(RAW.rglob("*")):
        if not f.is_file() or f.name.startswith("."):  # .gitkeep and the like
            continue
        rel = f.relative_to(ROOT).as_posix()
        if rel.startswith("raw/assets/"):
            assets.append(f"- `{rel}`")
        elif f.suffix == ".md" and rel not in referenced and rel not in superseded:
            meta, _ = split_frontmatter(f.read_text(encoding="utf-8-sig"))
            status = meta.get("fetch_status", "?")
            title = meta.get("title", "") or f.stem
            status_note = f" ({status})" if status != "full" else ""
            pending.append(f"- `{rel}`: {title}{status_note}")
    return pending, assets


def topic_block(slug, hub, pages):
    """One collapsed callout: the hub, then its pages by type. Obsidian folds it; the text stays greppable."""
    members = [p for p in pages if slug in p.topics and p is not hub]
    body = [line(hub)]
    for type_, spec in TYPES.items():
        group = sorted((p for p in members if p.type == type_), key=lambda p: p.name.lower())
        if not group:
            continue
        label = spec.get("label", type_.capitalize())
        if type_ == "source":
            for kind in ("primary", "secondary"):
                sub = [p for p in group if p.meta.get("kind") == kind]
                if sub:
                    body += ["", f"**{label}: {kind}**"] + [line(p) for p in sub]
            rest = [p for p in group if p.meta.get("kind") not in ("primary", "secondary")]
            if rest:
                body += ["", f"**{label}: other**"] + [line(p) for p in rest]
        else:
            body += ["", f"**{label}**"] + [line(p) for p in group]
    title = f"> [!abstract]- {hub.name} (`{slug}`), {len(members)} pages"
    return ["", title] + [f"> {b}" if b else ">" for b in body]


def build(pages):
    registry = topic_registry(pages)
    ordered, hub_of = topic_order(registry)
    domain_of = topic_domains(registry)
    newest = max((str(p.meta.get("updated", "")) for p in pages), default="")
    out = ["---", "type: index", f"updated: {newest}", "---", f"# {CONFIG.get('name', 'Wiki')} Index", "",
           "Every wiki page, grouped by domain, then topic, then page type. Generated by `tools/build_index.py`",
           "from frontmatter; don't edit by hand. Start with a topic's hub. Each topic's page list is folded:",
           "click it to open, or search this file for the topic's name.", ""]
    # Groups: declared domains in order, then topics with no (or an unknown) domain.
    groups = [(d, DOMAINS[d]) for d in DOMAINS]
    leftover = [s for s, _ in ordered if domain_of[s] not in DOMAINS]
    if leftover:
        groups.append(("", {"name": "Other topics" if DOMAINS else "Topics"}))

    def in_group(d):
        return [(s, depth) for s, depth in ordered if (domain_of[s] if domain_of[s] in DOMAINS else "") == d]

    out.append("**Map**")
    for d, spec in groups:
        members = in_group(d)
        if not members:
            continue
        desc = f": {spec['description']}" if spec.get("description") else ""
        out.append(f"- **{spec['name']}**{desc}")
        for slug, depth in members:
            hub = hub_of[slug]
            dormant = " (dormant)" if hub.meta.get("status") == "dormant" else ""
            out.append(f"{'  ' * (depth + 1)}- [[{hub.name}]] (`{slug}`){dormant}: {hub.summary}")
    for d, spec in groups:
        members = in_group(d)
        if not members:
            continue
        out += ["", f"## {spec['name']}"]
        for slug, _ in members:
            out += topic_block(slug, hub_of[slug], pages)
    orphans = [p for p in pages if not any(t in registry for t in p.topics)]
    if orphans:
        out += ["", "## No topic", ""] + [line(p) for p in sorted(orphans, key=lambda p: p.name.lower())]
    pending, assets = raw_sections(pages)
    if pending:
        out += ["", "## Raw files not yet ingested", ""] + pending
    if assets:
        out += ["", "## Assets (linked from pages; not sources)", ""] + assets
    return "\n".join(out) + "\n"


def main():
    utf8_stdout()
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="regenerate wiki/index.md")
    args = ap.parse_args()

    target = WIKI / "index.md"
    new = build(wiki_pages())
    old = target.read_text(encoding="utf-8") if target.exists() else ""
    if new == old:
        print("index.md is up to date")
    elif args.write:
        with open(target, "w", encoding="utf-8", newline="") as f:
            f.write(new)
        print("index.md regenerated")
    else:
        print("index.md is out of date (run with --write to regenerate)")


if __name__ == "__main__":
    main()
