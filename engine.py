"""Create vaults from the wiki engine and keep their engine files up to date.

Engine-owned files live under files/, at the paths they take inside a vault. A vault records which engine
version it's on, and a hash of each engine file as last synced, in meta/ENGINE. Sync uses those hashes to tell
an engine update (safe to apply) from an edit made inside the vault (refused unless --force).

Usage:
  python engine.py sync <vault>              # dry run: what would change
  python engine.py sync <vault> --write      # apply, and rewrite meta/ENGINE
  python engine.py sync <vault> --write --force   # also overwrite files edited inside the vault
  python engine.py init <new-folder> --name "Home Palace"   # new vault from template/, then sync, then git init

Standard library only. Never touches raw/ or wiki/ content, except init's empty skeleton.
"""
import argparse
import hashlib
import subprocess
import sys
from datetime import date
from pathlib import Path

ENGINE = Path(__file__).resolve().parent
FILES = ENGINE / "files"
TEMPLATE = ENGINE / "template"
MANIFEST = "meta/ENGINE"
SKIP = {"__pycache__"}


def version():
    return (ENGINE / "ENGINE_VERSION").read_text(encoding="utf-8").strip()


def digest(data):
    return hashlib.sha256(data).hexdigest()[:16]


def tree(root):
    """Relative posix path -> bytes, for every file under root."""
    return {p.relative_to(root).as_posix(): p.read_bytes()
            for p in sorted(root.rglob("*")) if p.is_file() and not SKIP & set(p.parts)}


def read_manifest(vault):
    path = vault / MANIFEST
    hashes, ver = {}, None
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("version:"):
                ver = line.split(":", 1)[1].strip()
            elif line and not line.startswith("#") and " " in line:
                h, rel = line.split(" ", 1)
                hashes[rel] = h
    return ver, hashes


def write_manifest(vault, files):
    lines = ["# Generated by the wiki engine's engine.py sync; don't edit. Engine-owned files, as last synced.",
             f"version: {version()}", ""]
    lines += [f"{digest(data)} {rel}" for rel, data in sorted(files.items())]
    (vault / MANIFEST).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def plan(vault, force):
    """Actions for a sync: (action, path) with action in add, update, remove, conflict, overwrite."""
    engine_files = tree(FILES)
    _, synced = read_manifest(vault)
    actions = []
    for rel, data in engine_files.items():
        target = vault / rel
        if not target.is_file():
            actions.append(("add", rel))
            continue
        current = target.read_bytes()
        if current == data:
            continue
        clean = synced.get(rel) == digest(current)
        actions.append(("update" if clean else ("overwrite" if force else "conflict"), rel))
    for rel, h in synced.items():
        if rel in engine_files:
            continue
        target = vault / rel
        if not target.is_file():
            continue
        clean = digest(target.read_bytes()) == h
        actions.append(("remove" if clean else ("overwrite" if force else "conflict"), rel))
    return engine_files, actions


def sync(vault, write, force):
    if not (vault / "meta" / "vault.json").is_file():
        sys.exit(f"{vault} has no meta/vault.json; is it a vault? (use init for a new one)")
    old_version, _ = read_manifest(vault)
    engine_files, actions = plan(vault, force)
    print(f"Engine {version()} -> {vault} (vault is on {old_version or 'no engine version'})")
    for action, rel in actions:
        note = {"conflict": "  (edited in the vault, or not engine-managed yet; --force overwrites)",
                "overwrite": "  (overwriting a change made in the vault)"}.get(action, "")
        print(f"  {action:9} {rel}{note}")
    if not actions:
        print("  engine files are up to date")
    conflicts = [rel for action, rel in actions if action == "conflict"]
    if not write:
        if actions:
            print("Dry run. Run with --write to apply.")
        return
    if conflicts:
        sys.exit(f"Refusing: {len(conflicts)} conflict(s). Move vault edits into the engine or Schema.md, or use --force.")
    for action, rel in actions:
        target = vault / rel
        if action == "remove" or (action == "overwrite" and rel not in engine_files):
            target.unlink()
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(engine_files[rel])
    write_manifest(vault, engine_files)
    print(f"Applied. meta/ENGINE records version {version()}. Commit as 'Engine: sync to {version()}'.")


def init(vault, name):
    if vault.exists() and any(vault.iterdir()):
        sys.exit(f"{vault} exists and isn't empty")
    today = date.today().isoformat()
    for rel, data in tree(TEMPLATE).items():
        target = vault / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.suffix in {".md", ".json"}:
            text = data.decode("utf-8")
            text = text.replace("{{NAME}}", name).replace("{{DATE}}", today).replace("{{VERSION}}", version())
            data = text.encode("utf-8")
        target.write_bytes(data)
    print(f"Created {vault} from template/")
    sync(vault, write=True, force=False)
    if not (vault / ".git").exists():
        subprocess.run(["git", "init", "-q", str(vault)], check=True)
        print("git init done (no remote). Next: python tools/build_index.py --write, then commit.")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sync", help="update a vault's engine files")
    s.add_argument("vault", type=Path)
    s.add_argument("--write", action="store_true")
    s.add_argument("--force", action="store_true")
    i = sub.add_parser("init", help="create a new vault")
    i.add_argument("vault", type=Path)
    i.add_argument("--name", required=True)
    args = ap.parse_args()
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8")
        except AttributeError:
            pass
    if args.cmd == "sync":
        sync(args.vault.resolve(), args.write, args.force)
    else:
        init(args.vault.resolve(), args.name)


if __name__ == "__main__":
    main()
